#!/usr/bin/env python3
"""Run verse-attribution evaluation on a dev seed and fresh held-out seeds; write docs/evidence/ATTRIBUTION_HELDOUT.md.

    python eval/finalize_evidence.py                     # dev=7, held-out=11,23,37 (n=300 each)
    python eval/finalize_evidence.py --lookup-file X.py  # evaluate an alternative implementation

Numbers come straight from section_attribution; nothing is typed by hand. Held-out seeds are pooled.
The dev seed (7) is where defects were found and fixed, so it is reported separately and is NOT an independent estimate.
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("run_eval", ROOT / "eval" / "run_eval.py")
run_eval = importlib.util.module_from_spec(spec)
spec.loader.exec_module(run_eval)

VARIANTS = ["prefix6", "middle4", "typo", "typo_mid", "swap"]
TITLES = {"prefix6": "first 6 words (EASY)", "middle4": "middle 4 words", "typo": "last letter of a word dropped",
          "typo_mid": "a middle letter dropped", "swap": "two adjacent letters swapped"}


def fmt(k: int, n: int) -> str:
    if n == 0:
        return "n/a"
    lo, hi = run_eval.wilson(k, n)
    return f"{k}/{n} ({100 * k / n:.1f}%, CI {lo}–{hi})"


def pooled(runs: list[dict]) -> dict:
    out = {}
    for v in VARIANTS:
        rows = [r["counts"][v] for r in runs]
        out[v] = {key: sum(x[key] for x in rows) for key in ("answered", "correct", "abstained", "in_candidates", "n")}
    out["chimera"] = {key: sum(r["counts"]["chimera"][key] for r in runs) for key in ("accepted", "n")}
    return out


def table(c: dict) -> list[str]:
    rows = ["| Variant | Coverage (answered) | Answered-accuracy | Abstained, true poet among candidates |", "|---|---|---|---|"]
    for v in VARIANTS:
        x = c[v]
        rows.append(f"| {TITLES[v]} | {fmt(x['answered'], x['n'])} | {fmt(x['correct'], x['answered'])} | {fmt(x['in_candidates'], x['abstained'])} |")
    ch = c["chimera"]
    rows.append(f"| chimera verses wrongly accepted | {fmt(ch['accepted'], ch['n'])} | | |")
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dev-seed", type=int, default=7)
    ap.add_argument("--heldout-seeds", type=int, nargs="+", default=[11, 23, 37])
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--lookup-file", default=None)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "evidence" / "ATTRIBUTION_HELDOUT.md")
    args = ap.parse_args()

    def run(seed):
        r = run_eval.section_attribution(args.n, seed, args.lookup_file)
        if r.get("status") == "SKIPPED":
            print("SKIPPED:", r["reason"])
            raise SystemExit(1)
        return r

    dev = run(args.dev_seed)
    held = [run(sd) for sd in args.heldout_seeds]
    env = run_eval.env_info()
    lines = [f"# Verse attribution — dev vs held-out ({datetime.now():%Y-%m-%d})", "",
             f"Generated by `python eval/finalize_evidence.py`. Commit `{env['commit']}`; {env['cpu']}, {env['cores']} threads, {env['ram_gb']} GB RAM.",
             f"Lookup: `{args.lookup_file or 'app.knowledge.poetry_lookup'}`. n={args.n} random verses per seed. Intervals: 95% Wilson.", "",
             f"## Held-out (seeds {', '.join(map(str, args.heldout_seeds))}, pooled n={args.n * len(held)}) — use these", ""]
    lines += table(pooled(held))
    lines += ["", f"## Dev seed {args.dev_seed} (defects were found and fixed on this sample — not an independent estimate)", ""]
    lines += table({**{v: dev["counts"][v] for v in VARIANTS}, "chimera": dev["counts"]["chimera"]})
    lines += ["", "## Per-seed held-out coverage / answered-accuracy (stability check)", "", "| Seed | " + " | ".join(TITLES[v] for v in VARIANTS) + " |",
              "|---|" + "---|" * len(VARIANTS)]
    for sd, r in zip(args.heldout_seeds, held):
        cells = [f"{r['counts'][v]['answered']}/{r['counts'][v]['n']} · {r['counts'][v]['correct']}/{r['counts'][v]['answered']}" for v in VARIANTS]
        lines.append(f"| {sd} | " + " | ".join(cells) + " |")
    lines += ["", "Queries are derived from the database itself, so this measures retrieval and abstention behaviour, not accuracy on arbitrary",
              "user input; correctness is relative to the database's own attributions.", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwritten: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
