def load_facts() -> dict:
    if FACTS_PATH.exists():
        return json.loads(FACTS_PATH.read_text(encoding="utf-8"))
    return {}


def tell_story_about(place_name: str) -> str:
    """اگر مکانی در دانش موجود باشد، روایتش را برمی‌گرداند."""
    for name, story in PLACE_STORIES.items():
        if place_name.strip() in name or name in place_name.strip():
            return story
    return ""


def find_place_mentions(text: str) -> list:
    """در متن ورودی، اسم مکان‌های شناخته‌شده را پیدا می‌کند."""
    return [name for name in PLACE_STORIES if name in text]


def format_for_prompt(text: str) -> str:
    """برای تزریق به پرامپت مدل، مثل الگوی quran/poetry."""
    mentions = find_place_mentions(text)
    if not mentions:
        return ""
    parts = [f"روایت دربارهٔ {m}: {tell_story_about(m)}" for m in mentions]
    return "\n\n".join(parts)
